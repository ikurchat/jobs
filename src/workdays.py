"""
Российский производственный календарь.

Определяет рабочие/нерабочие дни с учётом:
- Обычных выходных (суббота/воскресенье)
- Государственных праздников
- Переносов выходных дней (рабочие субботы)

Данные обновляются ежегодно — добавлять новый год в HOLIDAYS и WORKING_WEEKENDS.
"""

from datetime import date

# Государственные праздники РФ (фиксированные + типичные переносы)
# Обновлять каждый год по постановлению Правительства
HOLIDAYS: dict[int, set[tuple[int, int]]] = {
    2025: {
        (1, 1), (1, 2), (1, 3), (1, 4), (1, 5), (1, 6), (1, 7), (1, 8),  # Новый год + Рождество
        (2, 23),  # День защитника Отечества
        (2, 24),  # перенос (вс 23.02 → пн 24.02)
        (3, 8),   # Международный женский день
        (3, 10),  # перенос (сб 08.03 → пн 10.03)
        (5, 1),   # Праздник Весны и Труда
        (5, 2),   # перенос
        (5, 9),   # День Победы
        (6, 12),  # День России
        (6, 13),  # перенос
        (11, 3),  # перенос (4.11 → 3.11)
        (11, 4),  # День народного единства
        (12, 31), # перенос на 31 декабря
    },
    2026: {
        (1, 1), (1, 2), (1, 3), (1, 4), (1, 5), (1, 6), (1, 7), (1, 8),  # Новый год + Рождество
        (2, 23),  # День защитника Отечества
        (3, 8),   # Международный женский день
        (3, 9),   # перенос (вс 08.03 → пн 09.03)
        (5, 1),   # Праздник Весны и Труда
        (5, 4),   # перенос
        (5, 9),   # День Победы
        (5, 11),  # перенос (сб 09.05 → пн 11.05)
        (6, 12),  # День России
        (11, 4),  # День народного единства
        (12, 31), # перенос
    },
}

# Рабочие субботы/воскресенья (переносы)
WORKING_WEEKENDS: dict[int, set[tuple[int, int]]] = {
    2025: set(),
    2026: set(),
}


def is_workday(d: date | None = None) -> bool:
    """Является ли день рабочим по производственному календарю РФ.

    Логика:
    1. Если день в WORKING_WEEKENDS — рабочий (даже если суббота/воскресенье)
    2. Если день в HOLIDAYS — нерабочий
    3. Если суббота/воскресенье — нерабочий
    4. Иначе — рабочий
    """
    if d is None:
        d = date.today()

    year = d.year
    md = (d.month, d.day)

    # Рабочие выходные (переносы)
    if year in WORKING_WEEKENDS and md in WORKING_WEEKENDS[year]:
        return True

    # Праздники
    if year in HOLIDAYS and md in HOLIDAYS[year]:
        return False

    # Обычные выходные (суббота=5, воскресенье=6)
    if d.weekday() >= 5:
        return False

    return True


def is_holiday(d: date | None = None) -> bool:
    """Является ли день нерабочим."""
    return not is_workday(d)
